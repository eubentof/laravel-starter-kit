<?php

namespace App\Console\Commands;

use App\DataTables\Enums\CellType;
use App\DataTables\Enums\FilterType;
use App\Forms\Enums\FormFieldType;
use BackedEnum;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

final class GenerateTypeScriptContractsCommand extends Command
{
    protected $signature = 'typescript:transform';

    protected $description = 'Generate authoritative frontend contracts from PHP enums and DTO shapes';

    public function handle(): int
    {
        $types = strtr($this->template(), [
            '{{formFieldType}}' => $this->union(FormFieldType::cases()),
            '{{cellType}}' => $this->union(CellType::cases()),
            '{{filterType}}' => $this->union(FilterType::cases()),
        ]);

        File::put(resource_path('js/types/generated.ts'), $types);
        $this->info('Generated resources/js/types/generated.ts');

        return self::SUCCESS;
    }

    /** @param list<BackedEnum> $cases */
    private function union(array $cases): string
    {
        return collect($cases)->map(fn (BackedEnum $case): string => "'{$case->value}'")->implode(' | ');
    }

    private function template(): string
    {
        return <<<'TS'
/* eslint-disable */
// Generated by `composer types`. Do not edit by hand.

export type LocalizedTextData = { translations: Record<string, string> };
export type ChoiceOptionData = { value: string | number; label: LocalizedTextData; description: LocalizedTextData | null };
export type FormFieldType = {{formFieldType}};
export type FormFieldData = { key: string; type: FormFieldType; label: LocalizedTextData; description: LocalizedTextData | null; required: boolean; options: ChoiceOptionData[]; provider: string | null; validation: string[]; settings: Record<string, unknown>; disabled: boolean };
export type FormPageData = { key: string; title: LocalizedTextData; fields: FormFieldData[]; description: LocalizedTextData | null };
export type FormSchemaData = { version: number; title: LocalizedTextData; pages: FormPageData[]; description: LocalizedTextData | null; confirmation: LocalizedTextData | null };
export type CellType = {{cellType}};
export type FilterType = {{filterType}};
export type DataTableColumnData = { field: string; label: string; cell: CellType; filter: FilterType | null; sortable: boolean; editable: boolean; visible: boolean; pinned: boolean; provider: string | null };
export type DataTableSchemaData = { name: string; columns: DataTableColumnData[]; rowKey: string; perPage: number; defaultSortField: string | null; defaultSortDirection: string; emptyTitle: string; emptyDescription: string | null };
export type FieldOptionData = { value: string | number; label: string; description: string | null };
TS;
    }
}
